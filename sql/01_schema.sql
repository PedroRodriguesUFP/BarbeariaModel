DROP SCHEMA IF EXISTS barbearia CASCADE;
CREATE SCHEMA barbearia;
SET search_path TO barbearia;

-- ---------------------------------------------------------------------
-- UTILIZADOR  (RD01, RD02, RN01)
-- Supertipo único com papel. UNIQUE (id, papel) permite que outras
-- tabelas validem o papel por chave estrangeira composta.
-- ---------------------------------------------------------------------
CREATE TABLE utilizador (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                varchar(120) NOT NULL,
    email               varchar(254) NOT NULL,
    palavra_passe_hash  varchar(255) NOT NULL,
    papel               varchar(10)  NOT NULL,
    telefone            varchar(20),
    nif                 char(9),
    biografia           text,
    ativo               boolean      NOT NULL DEFAULT true,

    CONSTRAINT uq_utilizador_email UNIQUE (email),                      -- RN01
    CONSTRAINT uq_utilizador_id_papel UNIQUE (id, papel),               -- alvo das FK compostas
    CONSTRAINT ck_utilizador_papel CHECK (papel IN ('admin','barbeiro','cliente')),
    CONSTRAINT ck_utilizador_email CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT ck_utilizador_nif CHECK (nif ~ '^[0-9]{9}$'),
    -- RD02: dados específicos só para o papel respetivo
    CONSTRAINT ck_utilizador_campos_cliente
        CHECK (papel = 'cliente'  OR (telefone IS NULL AND nif IS NULL)),
    CONSTRAINT ck_utilizador_campos_barbeiro
        CHECK (papel = 'barbeiro' OR biografia IS NULL)
);
-- NIF único entre clientes (quando existe)
CREATE UNIQUE INDEX uq_utilizador_nif ON utilizador (nif) WHERE nif IS NOT NULL;

-- ---------------------------------------------------------------------
-- CALENDARIO + CALENDARIO_DIA  (RD03, RN02)
-- dias_trabalho deixou de ser array (1NF) -> tabela calendario_dia.
-- barbeiro_papel é coluna gerada constante: a FK composta garante que
-- só utilizadores com papel 'barbeiro' têm calendário (RN02), sem trigger.
-- ---------------------------------------------------------------------
CREATE TABLE calendario (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barbeiro_id     integer NOT NULL,
    barbeiro_papel  varchar(10) GENERATED ALWAYS AS ('barbeiro') STORED,
    nome            varchar(80),
    hora_inicio     time NOT NULL,
    hora_fim        time NOT NULL,

    CONSTRAINT uq_calendario_barbeiro UNIQUE (barbeiro_id),             -- relação 1:1
    CONSTRAINT fk_calendario_barbeiro FOREIGN KEY (barbeiro_id, barbeiro_papel)
        REFERENCES utilizador (id, papel) ON DELETE CASCADE,            -- RN02
    CONSTRAINT ck_calendario_horas CHECK (hora_fim > hora_inicio)
);

CREATE TABLE calendario_dia (
    calendario_id   integer  NOT NULL REFERENCES calendario (id) ON DELETE CASCADE,
    dia_semana      smallint NOT NULL,                                  -- 1=segunda ... 7=domingo (ISO)
    PRIMARY KEY (calendario_id, dia_semana),
    CONSTRAINT ck_calendario_dia CHECK (dia_semana BETWEEN 1 AND 7)
);

-- ---------------------------------------------------------------------
-- SERVICO  (RD04)
-- ---------------------------------------------------------------------
CREATE TABLE servico (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             varchar(80) NOT NULL,
    descricao        text,
    preco            numeric(8,2) NOT NULL,
    duracao_minutos  integer NOT NULL,
    categoria        varchar(20) NOT NULL,
    ativo            boolean NOT NULL DEFAULT true,

    CONSTRAINT uq_servico_nome UNIQUE (nome),
    CONSTRAINT ck_servico_preco CHECK (preco >= 0),
    CONSTRAINT ck_servico_duracao CHECK (duracao_minutos > 0),
    CONSTRAINT ck_servico_categoria
        CHECK (categoria IN ('cabelo','barba','cabelo e barba','degradee','coloracao'))
);

-- ---------------------------------------------------------------------
-- BARBEIRO_SERVICO  (RN03) — N:M barbeiro habilitado a serviço
-- ---------------------------------------------------------------------
CREATE TABLE barbeiro_servico (
    barbeiro_id     integer NOT NULL,
    barbeiro_papel  varchar(10) GENERATED ALWAYS AS ('barbeiro') STORED,
    servico_id      integer NOT NULL REFERENCES servico (id),
    PRIMARY KEY (barbeiro_id, servico_id),
    CONSTRAINT fk_barbeiro_servico_barbeiro FOREIGN KEY (barbeiro_id, barbeiro_papel)
        REFERENCES utilizador (id, papel) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- PLANO_SUBSCRICAO  (RD06)
-- ---------------------------------------------------------------------
CREATE TABLE plano_subscricao (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            varchar(80) NOT NULL,
    preco_mensal    numeric(8,2) NOT NULL,
    cortes_por_mes  integer NOT NULL,
    ativo           boolean NOT NULL DEFAULT true,

    CONSTRAINT uq_plano_nome UNIQUE (nome),
    CONSTRAINT ck_plano_preco CHECK (preco_mensal >= 0),
    CONSTRAINT ck_plano_cortes CHECK (cortes_por_mes > 0)
);

-- ---------------------------------------------------------------------
-- SUBSCRICAO  (RD07)
-- ---------------------------------------------------------------------
CREATE TABLE subscricao (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id      integer NOT NULL,
    cliente_papel   varchar(10) GENERATED ALWAYS AS ('cliente') STORED,
    plano_id        integer NOT NULL REFERENCES plano_subscricao (id),
    data_inicio     date NOT NULL,
    data_fim        date,
    estado          varchar(10) NOT NULL DEFAULT 'ativa',

    CONSTRAINT fk_subscricao_cliente FOREIGN KEY (cliente_id, cliente_papel)
        REFERENCES utilizador (id, papel),
    CONSTRAINT ck_subscricao_estado CHECK (estado IN ('ativa','suspensa','cancelada','expirada')),
    CONSTRAINT ck_subscricao_datas CHECK (data_fim IS NULL OR data_fim >= data_inicio),
    CONSTRAINT ck_subscricao_expirada CHECK (estado <> 'expirada' OR data_fim IS NOT NULL)
);
-- Um cliente só pode ter uma subscrição ativa de cada vez
CREATE UNIQUE INDEX uq_subscricao_ativa_cliente ON subscricao (cliente_id) WHERE estado = 'ativa';

-- ---------------------------------------------------------------------
-- MARCACAO  (RD05, RN05)
-- Uma marcação tem 1..N serviços (tabela marcacao_servico).
-- ---------------------------------------------------------------------
CREATE TABLE marcacao (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id       integer NOT NULL,
    cliente_papel    varchar(10) GENERATED ALWAYS AS ('cliente')  STORED,
    barbeiro_id      integer NOT NULL,
    barbeiro_papel   varchar(10) GENERATED ALWAYS AS ('barbeiro') STORED,
    subscricao_id    integer REFERENCES subscricao (id),               -- NULL = marcação avulsa
    data             date NOT NULL,
    hora             time NOT NULL,                                    -- corrigido: obrigatória (ver correcoes-fase1.md)
    estado           varchar(10) NOT NULL DEFAULT 'pendente',

    CONSTRAINT fk_marcacao_cliente FOREIGN KEY (cliente_id, cliente_papel)
        REFERENCES utilizador (id, papel),
    CONSTRAINT fk_marcacao_barbeiro FOREIGN KEY (barbeiro_id, barbeiro_papel)
        REFERENCES utilizador (id, papel),
    CONSTRAINT ck_marcacao_estado CHECK (estado IN ('pendente','confirmada','cancelada','concluida')),
    CONSTRAINT uq_marcacao_id_barbeiro UNIQUE (id, barbeiro_id)         -- alvo da FK de avaliacao
);
-- Barbeiro não pode ter duas marcações não canceladas no mesmo instante de início
CREATE UNIQUE INDEX uq_marcacao_barbeiro_slot ON marcacao (barbeiro_id, data, hora)
    WHERE estado <> 'cancelada';
CREATE INDEX ix_marcacao_cliente ON marcacao (cliente_id);
CREATE INDEX ix_marcacao_data ON marcacao (data);

-- ---------------------------------------------------------------------
-- MARCACAO_SERVICO  — lista de serviços da marcação
-- preco_aplicado guarda o preço no momento da marcação (histórico fiel
-- mesmo que servico.preco mude). É atributo do relacionamento N:M.
-- ---------------------------------------------------------------------
CREATE TABLE marcacao_servico (
    marcacao_id     integer NOT NULL REFERENCES marcacao (id) ON DELETE CASCADE,
    servico_id      integer NOT NULL REFERENCES servico (id),
    preco_aplicado  numeric(8,2) NOT NULL,
    PRIMARY KEY (marcacao_id, servico_id),
    CONSTRAINT ck_marcacao_servico_preco CHECK (preco_aplicado >= 0)
);
CREATE INDEX ix_marcacao_servico_servico ON marcacao_servico (servico_id);

-- ---------------------------------------------------------------------
-- PAGAMENTO  (RD08, RN04)
-- num_nonnulls(...) = 1  ->  exatamente uma origem (marcação XOR subscrição)
-- ---------------------------------------------------------------------
CREATE TABLE pagamento (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marcacao_id     integer REFERENCES marcacao (id),
    subscricao_id   integer REFERENCES subscricao (id),
    montante        numeric(8,2) NOT NULL,
    metodo          varchar(15) NOT NULL,
    estado          varchar(12) NOT NULL DEFAULT 'pendente',
    data_pagamento  timestamp,

    CONSTRAINT ck_pagamento_origem_unica CHECK (num_nonnulls(marcacao_id, subscricao_id) = 1),  -- RN04
    CONSTRAINT ck_pagamento_montante CHECK (montante > 0),
    CONSTRAINT ck_pagamento_metodo CHECK (metodo IN ('numerario','cartao','mbway','transferencia')),
    CONSTRAINT ck_pagamento_estado CHECK (estado IN ('pendente','pago','falhado','reembolsado')),
    CONSTRAINT ck_pagamento_data CHECK (estado NOT IN ('pago','reembolsado') OR data_pagamento IS NOT NULL)
);
CREATE INDEX ix_pagamento_marcacao ON pagamento (marcacao_id);
CREATE INDEX ix_pagamento_subscricao ON pagamento (subscricao_id);

-- ---------------------------------------------------------------------
-- AVALIACAO  (RD09, RN06)
-- Incide sobre uma marcação e exatamente UM alvo: barbeiro XOR serviço.
-- FK compostas garantem que o alvo avaliado participou mesmo na marcação.
-- ---------------------------------------------------------------------
CREATE TABLE avaliacao (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marcacao_id     integer NOT NULL,
    barbeiro_id     integer,
    servico_id      integer,
    classificacao   smallint NOT NULL,
    comentario      text,

    CONSTRAINT ck_avaliacao_classificacao CHECK (classificacao BETWEEN 1 AND 5),
    CONSTRAINT ck_avaliacao_alvo_unico CHECK (num_nonnulls(barbeiro_id, servico_id) = 1),  -- RN06
    CONSTRAINT fk_avaliacao_barbeiro FOREIGN KEY (marcacao_id, barbeiro_id)
        REFERENCES marcacao (id, barbeiro_id) ON DELETE CASCADE,
    CONSTRAINT fk_avaliacao_servico FOREIGN KEY (marcacao_id, servico_id)
        REFERENCES marcacao_servico (marcacao_id, servico_id) ON DELETE CASCADE
);
-- Uma avaliação por (marcação, alvo)
CREATE UNIQUE INDEX uq_avaliacao_barbeiro ON avaliacao (marcacao_id, barbeiro_id) WHERE barbeiro_id IS NOT NULL;
CREATE UNIQUE INDEX uq_avaliacao_servico  ON avaliacao (marcacao_id, servico_id)  WHERE servico_id  IS NOT NULL;
