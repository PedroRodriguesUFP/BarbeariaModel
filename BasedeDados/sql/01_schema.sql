-- =====================================================================
-- BarbeariaModel — BDAD 2026/27 (UFP) — Fase 2 (v2.0)
-- 01_schema.sql — esquema PostgreSQL unificado (alinhado com o Laravel)
--
-- Re-executável: apaga (DROP ... CASCADE) e recria só as tabelas do
-- modelo, no esquema "public" (o que o Laravel usa por omissão).
-- NÃO toca em tabelas de framework (migrations, sessions, ...).
-- Uso:  psql -d <bd> -v ON_ERROR_STOP=1 -f sql/01_schema.sql
--
-- Decisão D1 = Opção A: uma marcação tem UM serviço (appointments.service_id).
-- Rastreabilidade: cada restrição indica a RN/RD que implementa.
-- =====================================================================

BEGIN;
SET LOCAL client_min_messages = warning;   -- sem NOTICE do DROP ... IF EXISTS

DROP TABLE IF EXISTS reviews, payments, appointments, subscriptions,
                     subscription_plans, schedule_blocks, working_hours,
                     service_user, services, users CASCADE;

-- ---------------------------------------------------------------------
-- USERS (RD01, RD02, RN01)
-- Supertipo único com "role". UNIQUE (id, role) serve de alvo às FK
-- compostas que garantem o papel 'barber' (RN02) sem triggers.
-- password é opcional porque há contas com login externo (Google).
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    phone       VARCHAR(30),
    bio         TEXT,
    password    VARCHAR(255),
    role        VARCHAR(20)  NOT NULL,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_users_email   UNIQUE (email),                              -- RN01
    CONSTRAINT uq_users_id_role UNIQUE (id, role),                           -- alvo de FK compostas
    CONSTRAINT ck_users_role    CHECK (role IN ('admin', 'barber', 'client')),
    CONSTRAINT ck_users_email   CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);

-- ---------------------------------------------------------------------
-- SERVICES (RD04)
-- ---------------------------------------------------------------------
CREATE TABLE services (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255) NOT NULL,
    description      TEXT,
    price            NUMERIC(8,2) NOT NULL,
    duration_minutes INTEGER      NOT NULL,
    category         VARCHAR(30)  NOT NULL,
    is_active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_services_price    CHECK (price >= 0),
    CONSTRAINT ck_services_duration CHECK (duration_minutes > 0),
    CONSTRAINT ck_services_category
        CHECK (category IN ('hair', 'beard', 'hair and beard', 'fade', 'coloring'))
);

-- ---------------------------------------------------------------------
-- SERVICE_USER (RD10, RN02, RN03) — N:M barbeiro habilitado a serviço
-- user_role é uma coluna gerada constante: a FK composta só aceita
-- utilizadores com role 'barber' (RN02), sem trigger.
-- (O Laravel tem aqui um "id" substituto; a PK da cadeira é composta.)
-- ---------------------------------------------------------------------
CREATE TABLE service_user (
    user_id     BIGINT      NOT NULL,
    user_role   VARCHAR(20) GENERATED ALWAYS AS ('barber') STORED,
    service_id  BIGINT      NOT NULL,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (user_id, service_id),
    CONSTRAINT fk_service_user_barber  FOREIGN KEY (user_id, user_role)
        REFERENCES users (id, role) ON DELETE CASCADE,
    CONSTRAINT fk_service_user_service FOREIGN KEY (service_id)
        REFERENCES services (id) ON DELETE CASCADE
);
CREATE INDEX idx_service_user_service ON service_user (service_id);

-- ---------------------------------------------------------------------
-- WORKING_HOURS (RD03, RN02) — horário semanal (1=segunda ... 7=domingo)
-- ---------------------------------------------------------------------
CREATE TABLE working_hours (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL,
    user_role    VARCHAR(20) GENERATED ALWAYS AS ('barber') STORED,
    day_of_week  SMALLINT    NOT NULL,
    start_time   TIME        NOT NULL,
    end_time     TIME        NOT NULL,
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_working_hours_barber FOREIGN KEY (user_id, user_role)
        REFERENCES users (id, role) ON DELETE CASCADE,                       -- RN02
    CONSTRAINT ck_working_hours_day      CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_working_hours_interval CHECK (start_time < end_time),
    CONSTRAINT uq_working_hours_period   UNIQUE (user_id, day_of_week, start_time, end_time)
);

-- ---------------------------------------------------------------------
-- SCHEDULE_BLOCKS (RD03, RN02) — exceções ao horário: férias, folgas...
-- ---------------------------------------------------------------------
CREATE TABLE schedule_blocks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    user_role   VARCHAR(20) GENERATED ALWAYS AS ('barber') STORED,
    date        DATE        NOT NULL,
    start_time  TIME,
    end_time    TIME,
    all_day     BOOLEAN     NOT NULL DEFAULT FALSE,
    reason      VARCHAR(255),
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_schedule_blocks_barber FOREIGN KEY (user_id, user_role)
        REFERENCES users (id, role) ON DELETE CASCADE,                       -- RN02
    CONSTRAINT ck_schedule_block_times CHECK (
           (all_day AND start_time IS NULL AND end_time IS NULL)
        OR (NOT all_day AND start_time IS NOT NULL AND end_time IS NOT NULL
            AND start_time < end_time)
    )
);
CREATE INDEX idx_schedule_blocks_user_date ON schedule_blocks (user_id, date);

-- ---------------------------------------------------------------------
-- SUBSCRIPTION_PLANS (RD06)
-- ---------------------------------------------------------------------
CREATE TABLE subscription_plans (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255) NOT NULL,
    description    TEXT,
    monthly_price  NUMERIC(8,2) NOT NULL,
    cuts_per_month INTEGER      NOT NULL,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_subscription_plans_name UNIQUE (name),
    CONSTRAINT ck_plans_price CHECK (monthly_price >= 0),
    CONSTRAINT ck_plans_cuts  CHECK (cuts_per_month > 0)
);

-- ---------------------------------------------------------------------
-- SUBSCRIPTIONS (RD07, RN08)
-- UNIQUE (id, user_id) é o alvo da FK composta de appointments.
-- ---------------------------------------------------------------------
CREATE TABLE subscriptions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    subscription_plan_id  BIGINT      NOT NULL REFERENCES subscription_plans (id) ON DELETE RESTRICT,
    start_date            DATE        NOT NULL,
    end_date              DATE,
    status                VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at            TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_subscriptions_status CHECK (status IN ('active', 'suspended', 'cancelled', 'expired')),
    CONSTRAINT ck_subscriptions_dates  CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT uq_subscriptions_id_user UNIQUE (id, user_id)
);
-- RN08: no máximo uma subscrição ativa por utilizador
CREATE UNIQUE INDEX uq_one_active_subscription_per_user ON subscriptions (user_id) WHERE status = 'active';

-- ---------------------------------------------------------------------
-- APPOINTMENTS (RD05, RN03, RN05, RN07, RN09)
-- Opção A: um serviço por marcação.
-- customer_id é NULL nas marcações walk-in (cliente sem conta).
-- ---------------------------------------------------------------------
CREATE TABLE appointments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      BIGINT,
    walk_in_name     VARCHAR(255),
    walk_in_phone    VARCHAR(255),
    barber_id        BIGINT      NOT NULL,
    service_id       BIGINT      NOT NULL,
    subscription_id  BIGINT,                              -- NULL = avulsa; preenchido = coberta
    date             DATE        NOT NULL,
    time             TIME        NOT NULL,                -- a migration Laravel permite NULL (a corrigir)
    status           VARCHAR(20) NOT NULL DEFAULT 'pending',
    created_at       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_appointments_customer FOREIGN KEY (customer_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_barber   FOREIGN KEY (barber_id)   REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointments_service  FOREIGN KEY (service_id)  REFERENCES services (id) ON DELETE RESTRICT,
    -- RN03: o barbeiro só recebe marcações de serviços para que está habilitado
    CONSTRAINT fk_appointments_barber_service FOREIGN KEY (barber_id, service_id)
        REFERENCES service_user (user_id, service_id) ON DELETE RESTRICT,
    -- RN05: a subscrição que cobre a marcação pertence ao cliente da marcação
    CONSTRAINT fk_appointments_subscription_customer FOREIGN KEY (subscription_id, customer_id)
        REFERENCES subscriptions (id, user_id) ON DELETE RESTRICT,

    CONSTRAINT ck_appointments_status CHECK (status IN ('pending', 'confirmed', 'cancelled', 'completed')),
    -- RN09: ninguém marca consigo próprio (um barbeiro PODE ser cliente de outro barbeiro)
    CONSTRAINT ck_appointments_customer_not_barber CHECK (customer_id <> barber_id),
    -- RD05: ou há cliente com conta ou há nome do cliente walk-in
    CONSTRAINT ck_appointments_customer_or_walkin  CHECK (customer_id IS NOT NULL OR walk_in_name IS NOT NULL),
    -- consequência de RN05: sem cliente com conta não há subscrição
    -- (a FK composta com customer_id NULL não seria verificada)
    CONSTRAINT ck_appointments_subscription_needs_customer CHECK (subscription_id IS NULL OR customer_id IS NOT NULL)
);
-- RN07: um barbeiro não tem duas marcações ativas no mesmo instante de início
CREATE UNIQUE INDEX uq_appointments_barber_slot
    ON appointments (barber_id, date, time) WHERE status <> 'cancelled';
CREATE INDEX idx_appointments_customer_date ON appointments (customer_id, date);
CREATE INDEX idx_appointments_barber_date   ON appointments (barber_id, date);
CREATE INDEX idx_appointments_subscription  ON appointments (subscription_id);

-- ---------------------------------------------------------------------
-- PAYMENTS (RD08, RN04) — origem: marcação XOR subscrição
-- Sem payer_id: o pagador é appointments.customer_id ou subscriptions.user_id
-- (guardá-lo seria dependência transitiva — ver docs/fase2/02-normalizacao.md).
-- ---------------------------------------------------------------------
CREATE TABLE payments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id   BIGINT       REFERENCES appointments (id) ON DELETE RESTRICT,
    subscription_id  BIGINT       REFERENCES subscriptions (id) ON DELETE RESTRICT,
    amount           NUMERIC(8,2) NOT NULL,
    method           VARCHAR(20)  NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'pending',
    paid_at          TIMESTAMP,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_payments_single_origin CHECK (num_nonnulls(appointment_id, subscription_id) = 1),  -- RN04
    CONSTRAINT ck_payments_amount CHECK (amount >= 0),
    CONSTRAINT ck_payments_method CHECK (method IN ('cash', 'card', 'mbway', 'transfer')),
    CONSTRAINT ck_payments_status CHECK (status IN ('pending', 'paid', 'failed', 'refunded')),
    CONSTRAINT ck_payments_paid_at CHECK (status <> 'paid' OR paid_at IS NOT NULL)
);
CREATE INDEX idx_payments_appointment  ON payments (appointment_id);
CREATE INDEX idx_payments_subscription ON payments (subscription_id);

-- ---------------------------------------------------------------------
-- REVIEWS (RD09, RN06) — alvo: barbeiro XOR serviço
-- Decisão: NÃO ligada à marcação (nenhuma regra da Fase 1 ou da app o exige).
-- created_at funciona como data da avaliação (usada em Q01).
-- ---------------------------------------------------------------------
CREATE TABLE reviews (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reviewer_id  BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    barber_id    BIGINT,
    barber_role  VARCHAR(20) GENERATED ALWAYS AS ('barber') STORED,
    service_id   BIGINT      REFERENCES services (id) ON DELETE CASCADE,
    rating       SMALLINT    NOT NULL,
    comment      TEXT,
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- o barbeiro avaliado tem mesmo role 'barber' (barber_id NULL => não verificada)
    CONSTRAINT fk_reviews_barber FOREIGN KEY (barber_id, barber_role)
        REFERENCES users (id, role) ON DELETE CASCADE,
    CONSTRAINT ck_reviews_rating        CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_reviews_single_target CHECK (num_nonnulls(barber_id, service_id) = 1),      -- RN06
    CONSTRAINT ck_reviews_not_self      CHECK (barber_id IS NULL OR reviewer_id <> barber_id)
);
CREATE INDEX idx_reviews_barber   ON reviews (barber_id);
CREATE INDEX idx_reviews_service  ON reviews (service_id);
CREATE INDEX idx_reviews_reviewer ON reviews (reviewer_id);

COMMIT;
